"""Import vectors exported by the actual MCU C harness, retaining source hashes."""
import argparse
import hashlib
import json
from pathlib import Path
import tarfile

ROOT=Path(__file__).resolve().parents[2]


def main():
    p=argparse.ArgumentParser();p.add_argument('--mcu',type=Path,required=True)
    p.add_argument('--host-result',type=Path,required=True);args=p.parse_args()
    report=json.loads((args.host_result/'result.json').read_text())
    for name,digest in report['sources'].items():
        assert hashlib.sha256((args.mcu/name).read_bytes()).hexdigest()==digest,name
    data=(args.host_result/'vectors.bin').read_bytes()
    assert hashlib.sha256(data).hexdigest()==report['vectors_sha256']
    assert b'\r\r\n' not in data,'Windows text-mode newline expansion in vector export'
    fixture='# Generated by actual MCU test_stage6.c --vectors; do not hand edit.\n'
    fixture+='SOURCE_SHA256 = '+repr(report['sources'])+'\n'
    fixture+='VECTORS_SHA256 = '+repr(report['vectors_sha256'])+'\n'
    fixture+='VECTORS = '+repr(tuple(line+b'\r\n' for line in data.split(b'\r\n') if line))+'\n'
    (ROOT/'tests/diagnostic_vectors.py').write_text(fixture,encoding='utf-8')
    (ROOT/'tests/diagnostic_vectors.h').write_text('/* Actual MCU formatter vector; generated, do not hand edit. */\n'
        +'static const unsigned char diagnostic_test_vector[] = '+json.dumps(data.split(b'\r\n')[1].decode()+'\r\n')+';\n',encoding='utf-8')
    out=ROOT/'.local/stage6/mcu-reference.tar'
    names=set(report['sources'])
    for folder in ('Application/Inc','BSP/Inc','Components/SHT30/Inc'):
        names.update(p.relative_to(args.mcu).as_posix() for p in (args.mcu/folder).glob('*.h'))
    with tarfile.open(out,'w') as tar:
        for name in sorted(names):tar.add(args.mcu/name,arcname=name)
        tar.add(args.host_result/'result.json',arcname='host-result.json')
        tar.add(args.host_result/'vectors.bin',arcname='vectors.bin')
    print(json.dumps(dict(archive=str(out),vectors_sha256=report['vectors_sha256'],sources=len(names)),indent=2))


if __name__=='__main__':main()
